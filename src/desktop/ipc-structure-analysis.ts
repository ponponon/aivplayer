import { app, ipcMain } from 'electron'
import { createHash } from 'node:crypto'
import { mkdir, readFile, rename, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { execFileText } from '../core/child-process-registry'
import { buildMediaStructureSegments, DEFAULT_BLACK_PIXEL_THRESHOLD, DEFAULT_MIN_BLACK_DURATION_SECONDS, parseBlackIntervals } from '../core/media/structure-analysis'
import { resolveFfmpegPath } from '../core/ai/whisper-cpp-runtime'
import { IPC_CHANNELS } from '../shared/ipc-channels'
import type { MediaStructureAnalysisRequest, MediaStructureAnalysisResult } from '../shared/media-types'
import { resolveResourcePath } from './desktop-services'

const analysisQueues = new Map<string, Promise<MediaStructureAnalysisResult>>()
// Full-file blackdetect decodes every frame. Capping decoder threads keeps a
// user-triggered analysis from saturating the machine while playback continues.
const STRUCTURE_ANALYSIS_DECODER_THREADS = 4
const STRUCTURE_ANALYSIS_CACHE_MISS_MESSAGE = '结构分析缓存未命中'
const STRUCTURE_ANALYSIS_CANCELLED_MESSAGE = '结构分析已取消'

/** In-flight analyses keyed by media path so a cancel request can reach the running FFmpeg child. */
const activeAnalyses = new Map<string, AbortController>()

function hash(value: string): string {
  return createHash('sha256').update(value).digest('hex').slice(0, 24)
}

type NormalizedRequest = {
  mediaPath: string
  durationSeconds?: number
  minBlackDurationSeconds: number
  pixelThreshold: number
  cacheOnly: boolean
}

function normalizeRequest(request: MediaStructureAnalysisRequest): NormalizedRequest | null {
  if (!request || typeof request.mediaPath !== 'string' || !request.mediaPath.trim()) return null
  const durationSeconds = typeof request.durationSeconds === 'number' && Number.isFinite(request.durationSeconds) ? Math.max(0, request.durationSeconds) : undefined
  const minBlackDurationSeconds = typeof request.minBlackDurationSeconds === 'number' && Number.isFinite(request.minBlackDurationSeconds) ? Math.min(10, Math.max(0.1, request.minBlackDurationSeconds)) : DEFAULT_MIN_BLACK_DURATION_SECONDS
  const pixelThreshold = typeof request.pixelThreshold === 'number' && Number.isFinite(request.pixelThreshold) ? Math.min(0.5, Math.max(0.001, request.pixelThreshold)) : DEFAULT_BLACK_PIXEL_THRESHOLD
  return { mediaPath: request.mediaPath, durationSeconds, minBlackDurationSeconds, pixelThreshold, cacheOnly: request.cacheOnly === true }
}

type CacheTarget = { mediaStat: { size: number; mtimeMs: number }; sourceFingerprint: string; cacheKey: string; cacheDirectory: string; cachePath: string }

async function resolveCacheTarget(request: NormalizedRequest): Promise<CacheTarget | null> {
  let mediaStat
  try {
    mediaStat = await stat(request.mediaPath)
  } catch {
    return null
  }
  const sourceFingerprint = hash(`${request.mediaPath}|${mediaStat.size}|${mediaStat.mtimeMs}`)
  const cacheKey = hash(`${sourceFingerprint}|${request.durationSeconds ?? ''}|${request.minBlackDurationSeconds}|${request.pixelThreshold}`)
  const cacheDirectory = join(app.getPath('userData'), 'media-analysis', 'structure')
  return { mediaStat, sourceFingerprint, cacheKey, cacheDirectory, cachePath: join(cacheDirectory, `${cacheKey}.json`) }
}

async function readCachedSegments(target: CacheTarget): Promise<MediaStructureAnalysisResult | null> {
  try {
    const cached = JSON.parse(await readFile(target.cachePath, 'utf8')) as { sourceFingerprint?: unknown; segments?: unknown }
    if (cached.sourceFingerprint !== target.sourceFingerprint || !Array.isArray(cached.segments)) return null
    return { success: true, message: 'Structure analysis loaded from cache', cacheHit: true, cacheKey: target.cacheKey, segments: cached.segments as MediaStructureAnalysisResult['segments'] }
  } catch {
    // A damaged analysis cache is regenerated by a real analysis run.
    return null
  }
}

async function analyzeUnqueued(request: NormalizedRequest): Promise<MediaStructureAnalysisResult> {
  const target = await resolveCacheTarget(request)
  if (!target) return { success: false, message: 'Media file is unavailable', cacheHit: false, cacheKey: null, segments: [] }

  const cached = await readCachedSegments(target)
  if (cached) return cached
  if (request.cacheOnly) return { success: false, message: STRUCTURE_ANALYSIS_CACHE_MISS_MESSAGE, cacheHit: false, cacheKey: target.cacheKey, segments: [] }

  const ffmpegPath = await resolveFfmpegPath(resolveResourcePath(), process.env, undefined)
  if (!ffmpegPath) return { success: false, message: 'FFmpeg is unavailable', cacheHit: false, cacheKey: target.cacheKey, segments: [] }
  const filter = `blackdetect=d=${request.minBlackDurationSeconds}:pix_th=${request.pixelThreshold}`
  const controller = new AbortController()
  activeAnalyses.set(request.mediaPath, controller)
  try {
    const { stdout, stderr } = await execFileText(ffmpegPath, ['-hide_banner', '-loglevel', 'info', '-threads', String(STRUCTURE_ANALYSIS_DECODER_THREADS), '-i', request.mediaPath, '-vf', filter, '-an', '-f', 'null', '-'], { label: 'structure-blackdetect', role: 'analysis' }, { maxBuffer: 12 * 1024 * 1024, signal: controller.signal })
    if (controller.signal.aborted) return { success: false, message: STRUCTURE_ANALYSIS_CANCELLED_MESSAGE, cacheHit: false, cacheKey: target.cacheKey, segments: [] }
    const intervals = parseBlackIntervals(`${stdout}\n${stderr}`, request.durationSeconds, request.minBlackDurationSeconds)
    const segments = buildMediaStructureSegments(intervals, request.durationSeconds)
    await mkdir(target.cacheDirectory, { recursive: true })
    const temporaryPath = `${target.cachePath}.${process.pid}.tmp`
    await writeFile(temporaryPath, `${JSON.stringify({ schemaVersion: 1, sourceFingerprint: target.sourceFingerprint, mediaPath: request.mediaPath, sizeBytes: target.mediaStat.size, mtimeMs: target.mediaStat.mtimeMs, durationSeconds: request.durationSeconds, minBlackDurationSeconds: request.minBlackDurationSeconds, pixelThreshold: request.pixelThreshold, segments, updatedAt: new Date().toISOString() }, null, 2)}\n`, 'utf8')
    await rename(temporaryPath, target.cachePath)
    return { success: true, message: 'Structure analysis completed', cacheHit: false, cacheKey: target.cacheKey, segments }
  } catch (error) {
    if (controller.signal.aborted) return { success: false, message: STRUCTURE_ANALYSIS_CANCELLED_MESSAGE, cacheHit: false, cacheKey: target.cacheKey, segments: [] }
    const output = error && typeof error === 'object' && 'stderr' in error && typeof error.stderr === 'string' ? error.stderr : ''
    return { success: false, message: output.trim().slice(-500) || (error instanceof Error ? error.message : 'Structure analysis failed'), cacheHit: false, cacheKey: target.cacheKey, segments: [] }
  } finally {
    if (activeAnalyses.get(request.mediaPath) === controller) activeAnalyses.delete(request.mediaPath)
  }
}

/** Aborts every running structure analysis so no FFmpeg child outlives the window. */
export function cancelAllStructureAnalyses(): void {
  for (const controller of activeAnalyses.values()) controller.abort()
  activeAnalyses.clear()
}

function cancelStructureAnalysis(mediaPath: string): void {
  const controller = activeAnalyses.get(mediaPath)
  if (!controller) return
  activeAnalyses.delete(mediaPath)
  controller.abort()
}

export function registerStructureAnalysisIpc(): void {
  ipcMain.handle(IPC_CHANNELS.ANALYZE_MEDIA_STRUCTURE, async (_event, request: MediaStructureAnalysisRequest): Promise<MediaStructureAnalysisResult> => {
    const normalized = normalizeRequest(request)
    if (!normalized) return { success: false, message: 'Invalid structure analysis request', cacheHit: false, cacheKey: null, segments: [] }
    // A cache-only probe must never queue behind — or trigger — a full FFmpeg run.
    if (normalized.cacheOnly) return analyzeUnqueued(normalized)
    const queueKey = JSON.stringify(normalized)
    const previous = analysisQueues.get(queueKey) ?? Promise.resolve<MediaStructureAnalysisResult>({ success: false, message: 'No previous analysis', cacheHit: false, cacheKey: null, segments: [] })
    const next = previous.catch(() => ({ success: false, message: 'Previous analysis failed', cacheHit: false, cacheKey: null, segments: [] })).then(() => analyzeUnqueued(normalized))
    analysisQueues.set(queueKey, next)
    void next.then(() => { if (analysisQueues.get(queueKey) === next) analysisQueues.delete(queueKey) })
    return next
  })
  ipcMain.handle(IPC_CHANNELS.CANCEL_MEDIA_STRUCTURE_ANALYSIS, (_event, request: { mediaPath?: unknown }): void => {
    if (!request || typeof request.mediaPath !== 'string' || !request.mediaPath.trim()) return
    cancelStructureAnalysis(request.mediaPath)
  })
}
